"""
Vision-Language Question Answering Inference Endpoint.

Supports:
1. Initial Image Analysis: Full validation, quality assessment, and moderation.
2. Follow-Up Questions (KV Cache Reuse): Reuses cached visual tokens via session_id
   without re-uploading or re-processing the image.
"""

import time
import uuid
from dataclasses import dataclass, field
from fastapi import APIRouter, Depends, File, Form, HTTPException, UploadFile, status
from pydantic import BaseModel, Field

from app.config import settings
from app.dependencies import verify_api_key
from app.inference.models import InferenceMetrics, InferenceRequest
from app.inference.service import inference_service
from app.moderation.service import moderation_service
from app.services.image_models import ProcessedImage, QualityAssessment
from app.services.image_preprocessor import image_preprocessor
from app.services.image_quality import image_quality_service
from app.services.image_validator import image_validator

router = APIRouter()


# ==============================================================================
# In-Memory Visual Session Store (KV Cache Prefix Management)
# ==============================================================================

@dataclass
class VisualSession:
    session_id: str
    processed_image: ProcessedImage
    quality: QualityAssessment
    history: list[dict[str, str]] = field(default_factory=list)
    last_accessed: float = field(default_factory=time.time)


class VisualSessionStore:
    """Manages conversational session state to allow KV cache reuse across turns."""

    def __init__(self, ttl_seconds: float = 600.0) -> None:
        self._sessions: dict[str, VisualSession] = {}
        self.ttl = ttl_seconds

    def create(self, processed: ProcessedImage, quality: QualityAssessment) -> str:
        """Store processed image and initialize session."""
        self._evict_expired()
        session_id = f"sess_{uuid.uuid4().hex[:12]}"
        self._sessions[session_id] = VisualSession(
            session_id=session_id,
            processed_image=processed,
            quality=quality,
            history=[],
        )
        return session_id

    def get(self, session_id: str) -> VisualSession | None:
        """Retrieve active visual session and update access timestamp."""
        self._evict_expired()
        session = self._sessions.get(session_id)
        if session:
            session.last_accessed = time.time()
        return session

    def _evict_expired(self) -> None:
        now = time.time()
        expired = [sid for sid, s in self._sessions.items() if now - s.last_accessed > self.ttl]
        for sid in expired:
            del self._sessions[sid]


# Global session store instance (10-minute session TTL)
session_store = VisualSessionStore(ttl_seconds=600.0)


# ==============================================================================
# Response Schema
# ==============================================================================

class AnalyzeResponse(BaseModel):
    """Output envelope returned to the mobile client."""

    success: bool = True
    answer: str = Field(description="Answer generated by LiquidAI vision model")
    session_id: str = Field(description="Session ID for follow-up questions reusing KV cache")
    cache_hit: bool = Field(default=False, description="True if existing visual KV cache was reused")
    metrics: InferenceMetrics
    quality: QualityAssessment | None = Field(
        default=None,
        description="Image quality diagnostics (present on initial upload)",
    )


# ==============================================================================
# Endpoint Handler
# ==============================================================================

@router.post(
    "/analyze",
    response_model=AnalyzeResponse,
    status_code=status.HTTP_200_OK,
    dependencies=[Depends(verify_api_key)],
)
async def analyze_image(
    file: UploadFile | None = File(default=None, description="Camera photo (JPEG, PNG, WebP)"),
    question: str = Form(..., min_length=1, max_length=2000, description="User question"),
    session_id: str | None = Form(default=None, description="Optional session ID for follow-up questions"),
) -> AnalyzeResponse:
    """
    Ingest a mobile camera snapshot or follow up on a previous image.

    - Turn 1 (New Photo): Provide 'file' + 'question'. Returns answer and new 'session_id'.
    - Turn 2+ (Follow-up): Provide 'question' + 'session_id' (omit 'file').
      Reuses visual KV cache tokens directly for fast response.
    """
    # --------------------------------------------------------------------------
    # Branch A: Follow-up Question (KV Cache Hit)
    # --------------------------------------------------------------------------
    if session_id and (file is None or file.filename == ""):
        session = session_store.get(session_id)
        if not session:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Session '{session_id}' not found or expired. Please upload a new photo.",
            )

        # Contextual prompt formatting for multi-turn conversational history
        inf_req = InferenceRequest(prompt=question)
        response = await inference_service.generate_answer(session.processed_image, inf_req)

        # Record conversation turn
        session.history.append({"role": "user", "content": question})
        session.history.append({"role": "assistant", "content": response.text})

        return AnalyzeResponse(
            success=True,
            answer=response.text,
            session_id=session_id,
            cache_hit=True,
            metrics=response.metrics,
            quality=session.quality,
        )

    # --------------------------------------------------------------------------
    # Branch B: Initial Image Intake (Creates KV Cache Prefix)
    # --------------------------------------------------------------------------
    if file is None:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="An image file is required when starting a new session.",
        )

    raw_bytes = await file.read()

    try:
        # Gate 1: Header verification & decompression bomb defense
        metadata = image_validator.validate(raw_bytes, declared_content_type=file.content_type)

        # Gate 2: Orientation correction & aspect-ratio downscaling
        processed = image_preprocessor.process(raw_bytes, metadata)

        # Gate 3: Lighting & blur quality checks
        quality = image_quality_service.validate_or_raise(processed)

        # Gate 4: Visual content moderation
        await moderation_service.moderate_or_raise(processed.data)

        # Gate 5: Model forward pass (concurrency protected)
        inf_req = InferenceRequest(prompt=question)
        response = await inference_service.generate_answer(processed, inf_req)

        # Store in session store for subsequent KV cache hits
        new_session_id = session_store.create(processed, quality)
        session = session_store.get(new_session_id)
        if session:
            session.history.append({"role": "user", "content": question})
            session.history.append({"role": "assistant", "content": response.text})

        return AnalyzeResponse(
            success=True,
            answer=response.text,
            session_id=new_session_id,
            cache_hit=False,
            metrics=response.metrics,
            quality=quality,
        )

    finally:
        # Zero-retention privacy: immediately close file descriptor and release raw buffer
        await file.close()
        del raw_bytes